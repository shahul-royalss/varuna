from varuna_schemas.models.city import RadarDomain
from varuna_schemas.models.common import BBox

BUNDLE_ID = "MUM-2019-07-02"
DESIGN_ID = "MUM-IDF-25yr"
T0 = datetime(2019, 7, 2, 5, 40, tzinfo=IST)
T1 = datetime(2019, 7, 2, 9, 40, tzinfo=IST)
AOI = BBox(min_lon=72.815, min_lat=18.995, max_lon=72.905, max_lat=19.135)
RADAR = RadarDomain(center_lon=72.86, center_lat=19.065, size_km=60.0, res_m=500.0)
CADENCES = {
    "radar": 10,
    "truth": 5,
    "gauges": 15,
    "tide": 15,
    "traffic": 5,
    "reports": 5,
    "cycle": 5,
}

MEMBERS = (
    "radar/frames.zarr",
    "truth/rain.zarr",
    "gauges.csv",
    "tide.csv",
    "traffic/speeds.parquet",
    "reports.jsonl",
    "ground_truth.geojson",
)


def _manifest(bundle_id: str, label: str) -> BundleManifest:
    sources = (
        [
            BundleSource(
                name="IMD Santacruz 24-hour total, 2 July 2019",
                url="https://mausam.imd.gov.in/mumbai/mcdata/Highest_Scz_July.gif",
                note="375.2 mm for the 24 hours ending 08:30 IST",
                used_for="Window accumulation target",
            )
        ]
        if label == "Reconstructed replay"
        else []
    )
    return BundleManifest(
        id=bundle_id,
        city="mumbai",
        label=label,  # type: ignore[arg-type]
        t0=T0,
        t1=T1,
        cadences=CADENCES,
        radar_domain=RADAR,
        aoi=AOI,
        sources=sources,
        seed=2019,
        synthetic_notes=["Radar frames: storm-designer reconstruction."],
        ground_truth_n=29,
        description="Reconstructed replay of the 2 July 2019 morning.",
    )


def _write_bundle(root: Path, bundle_id: str, label: str, *, complete: bool) -> Path:
    folder = root / bundle_id
    folder.mkdir(parents=True, exist_ok=True)
    manifest = _manifest(bundle_id, label)
    (folder / "manifest.json").write_text(
        manifest.model_dump_json(indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    if complete:
        for member in MEMBERS:
            path = folder / member
            path.parent.mkdir(parents=True, exist_ok=True)
            if member.endswith(".zarr"):
                path.mkdir(exist_ok=True)
            else:
                path.write_text("", encoding="utf-8", newline="\n")
    return folder


