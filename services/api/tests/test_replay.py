"""Contract tests for the replay routes (CLAUDE.md 12; task P2.7).

The bundles here are folders with a manifest and empty members: ``GET /v1/replay/bundles``
reports which members are *present*, and ``varuna bundle validate`` is what reads them. That
split is deliberate, so the replay page can say "Generated by make bundle" about a folder that
does not exist yet without loading a Zarr store to find out.
"""

