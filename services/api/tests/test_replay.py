def test_play_and_pause_move_the_shared_clock(client: TestClient) -> None:
    played = client.post("/v1/replay/play").json()
    assert played["playing"] is True

    paused = client.post("/v1/replay/pause").json()
    assert paused["playing"] is False
    assert paused["sim_time"] >= T0.isoformat()
    assert client.get("/v1/replay/clock").json()["sim_time"] == paused["sim_time"]


def test_seek_clamps_to_the_window_instead_of_refusing(client: TestClient) -> None:
    inside = (T0 + timedelta(minutes=60)).isoformat()
    assert client.post("/v1/replay/seek", json={"sim_time": inside}).json()["sim_time"] == inside

    late = client.post("/v1/replay/seek", json={"sim_time": "2019-07-02T23:00:00+05:30"}).json()
    assert late["sim_time"] == T1.isoformat()

    early = client.post("/v1/replay/seek", json={"sim_time": "2019-07-01T00:00:00+05:30"}).json()
    assert early["sim_time"] == T0.isoformat()


def test_speed_accepts_what_the_time_bar_offers_and_explains_what_it_does_not(
    client: TestClient,
) -> None:
    assert client.post("/v1/replay/speed", json={"speed": 60}).json()["speed"] == 60

    res = client.post("/v1/replay/speed", json={"speed": 7})
    assert res.status_code == 422
    error = res.json()["error"]
    assert error["code"] == "invalid_speed"
    assert "1, 10, 30, 60" in error["message"]
    assert client.get("/v1/replay/clock").json()["speed"] == 60


def test_selecting_another_bundle_moves_the_clock_to_its_window(client: TestClient) -> None:
    clock = client.post("/v1/replay/bundle", json={"bundle_id": DESIGN_ID}).json()
    assert clock["bundle_id"] == DESIGN_ID
    assert clock["playing"] is False
    assert client.get("/v1/replay/clock").json()["bundle_id"] == DESIGN_ID


def test_an_unknown_bundle_says_which_make_target_generates_it(client: TestClient) -> None:
    res = client.post("/v1/replay/bundle", json={"bundle_id": "MUM-2020-08-05"})
    assert res.status_code == 404
    error = res.json()["error"]
    assert error["code"] == "bundle_not_found"
    assert "make bundle BUNDLE=MUM-2020-08-05" in error["message"]
    assert BUNDLE_ID in error["message"]  # what is on disk instead

    assert client.get("/v1/replay/clock", params={"bundle": "MUM-2020-08-05"}).status_code == 404


