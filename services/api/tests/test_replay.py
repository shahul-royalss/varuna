def bundles(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A bundles folder holding one complete-looking bundle and one that is only a manifest."""
    root = tmp_path / "bundles"
    monkeypatch.setenv("VARUNA_BUNDLES_DIR", str(root))
    _write_bundle(root, BUNDLE_ID, "Reconstructed replay", complete=True)
    _write_bundle(root, DESIGN_ID, "Design storm", complete=False)
    return root


