def test_bundles_lists_what_is_on_disk_with_build_and_bake_status(client: TestClient) -> None:
    rows = client.get("/v1/replay/bundles").json()
    assert [row["id"] for row in rows] == [BUNDLE_ID, DESIGN_ID]  # sorted by id

    demo = next(row for row in rows if row["id"] == BUNDLE_ID)
    assert demo["label"] == "Reconstructed replay"
    assert demo["city"] == "mumbai"
    assert demo["t0"] == T0.isoformat()
    assert demo["t1"] == T1.isoformat()
    assert demo["built"] is True
    assert demo["missing_members"] == []
    assert demo["total_cycles"] == 49  # 4 hours of 5-minute cycles, inclusive
    assert demo["baked"] is False
    assert demo["baked_cycles"] == 0
    assert demo["ground_truth_n"] == 29
    assert demo["sources_n"] == 1

    design = next(row for row in rows if row["id"] == DESIGN_ID)
    assert design["built"] is False
    assert design["missing_members"] == ["radar/frames.zarr", "truth/rain.zarr"]


